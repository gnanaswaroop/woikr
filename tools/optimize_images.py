"""Shrink oversized images under site/static in place (same path, same format).

An image is processed when it is over 150 KB or wider/taller than 1600 px.
Images are scaled to at most 1600 px on the long side and re-encoded
(JPEG: quality 82, progressive; PNG: optimised). A file is only replaced when
the result is smaller. GIFs and anything Pillow cannot read are left alone.

Usage (repo root):
  python tools/optimize_images.py --dry-run   # report only
  python tools/optimize_images.py             # convert
"""
import os
import sys

from PIL import Image, ImageOps

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
STATIC = os.path.join(ROOT, "site", "static")
SKIP_DIRS = {"thumbs"}  # generated by make_thumbs.py
EXTS = {".jpg", ".jpeg", ".png"}
MAX_SIDE = 1600
MAX_BYTES = 150 * 1024
PNG_PALETTE_BYTES = 300 * 1024


def candidates():
    for dp, dn, fn in os.walk(STATIC):
        dn[:] = [d for d in dn if d not in SKIP_DIRS]
        for f in fn:
            p = os.path.join(dp, f)
            if os.path.splitext(f)[1].lower() in EXTS:
                yield p


def optimise(path, dry):
    before = os.path.getsize(path)
    try:
        with Image.open(path) as im:
            fmt = im.format
            im = ImageOps.exif_transpose(im)
            big_side = max(im.size) > MAX_SIDE
            if before <= MAX_BYTES and not big_side:
                return "ok", before, before
            if big_side:
                scale = MAX_SIDE / max(im.size)
                im = im.resize((round(im.width * scale), round(im.height * scale)), Image.LANCZOS)
            if dry:
                return "would", before, before
            tmp = path + ".tmp"
            if fmt == "JPEG":
                im.convert("RGB").save(tmp, "JPEG", quality=82, progressive=True, optimize=True)
            elif fmt == "PNG":
                im.save(tmp, "PNG", optimize=True)
                if os.path.getsize(tmp) > PNG_PALETTE_BYTES:
                    # Large screenshots/graphics: a 256-colour palette keeps them looking right and is much smaller.
                    im.quantize(colors=256, method=Image.Quantize.FASTOCTREE).save(tmp, "PNG", optimize=True)
            else:
                return "skip", before, before
    except Exception as e:
        print("skip", path, e, file=sys.stderr)
        return "skip", before, before
    after = os.path.getsize(tmp)
    if after < before:
        os.replace(tmp, path)
        return "done", before, after
    os.remove(tmp)
    return "kept", before, before


def main():
    dry = "--dry-run" in sys.argv
    stats = {}
    saved = 0
    for p in candidates():
        status, b, a = optimise(p, dry)
        stats[status] = stats.get(status, 0) + 1
        saved += b - a
    print("result:", stats, "| bytes saved:", round(saved / 1048576, 1), "MB")


if __name__ == "__main__":
    main()
